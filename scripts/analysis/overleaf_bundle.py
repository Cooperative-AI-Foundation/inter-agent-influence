# Task #7 modules (aar.py, leaderboard_by_target.py, technique_plots.py) are
# now fixed and their figures live in the canonical lists above — nothing
# pending. (Kept as empty hooks so run() needs no change.)
PENDING_TASK7_SOURCES: tuple[Path, ...] = ()
PENDING_TASK7_RENAMED: dict[Path, str] = {}


def _copy(src: Path, dst: Path, copied: dict[str, Path], key: str) -> bool:
    if not src.exists():
        return False
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)
    copied[key] = dst
    return True


def run(out_dir: Path | None = None) -> dict[str, Path]:
    out_dir = out_dir or (ANALYSIS_DIR / "overleaf")
    figures_dir = out_dir / "figures"
    out_dir.mkdir(parents=True, exist_ok=True)
    figures_dir.mkdir(parents=True, exist_ok=True)

    copied: dict[str, Path] = {}
    missing: list[Path] = []           # canonical sources that should exist
    pending: list[Path] = []           # Task #7 sources (expected absent for now)

    # NOTE: methods.tex is no longer bundled — the methods appendix is
    # hand-authored on Overleaf (appendix/methods.tex), not pipeline-generated.

    # figures/ — same-name copies (canonical).
    for src in FIGURES_SOURCES:
        if not _copy(src, figures_dir / src.name, copied, f"figures/{src.name}"):
            missing.append(src)

    # figures/ — renamed / subdir copies (canonical).
    for src, dst_name in FIGURES_RENAMED.items():
        if not _copy(src, figures_dir / dst_name, copied, f"figures/{dst_name}"):
            missing.append(src)

    # figures/ — Task #7 pending (do not alarm if absent).
    for src in PENDING_TASK7_SOURCES:
        if not _copy(src, figures_dir / src.name, copied, f"figures/{src.name}"):
            pending.append(src)
    for src, dst_name in PENDING_TASK7_RENAMED.items():
        if not _copy(src, figures_dir / dst_name, copied, f"figures/{dst_name}"):
            pending.append(src)

    print(f"Overleaf bundle written to {out_dir.relative_to(ROOT)}/")
    print(f"  {len(copied)} files copied under figures/")
    if missing:
        print()
        print(f"  ⚠ {len(missing)} expected source(s) MISSING "
              f"(run `make pipeline && make pipeline-standalone` first):")
        for p in missing:
            print(f"    - {p.relative_to(ROOT)}")
    if pending:
        print()
        print(f"  ⏳ {len(pending)} source(s) pending Task #7 "
              f"(aar.py / technique_plots.py / leaderboard_by_target.py):")
        for p in pending:
            print(f"    - {p.relative_to(ROOT)}")
    print()
    print(f"To upload: drop the figures/ subfolder "
          f"({out_dir.relative_to(ROOT)}/figures/) into your Overleaf project root.")

    return copied


if __name__ == "__main__":
    run()
